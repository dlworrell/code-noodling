# Host -> (PEM, expected SHA-256 of the DER certificate).
EXTRA_INTERMEDIATES = {
    "www.elections.alaska.gov": (
        GLOBALSIGN_GCC_R46_OV_TLS_CA_2025,
        GLOBALSIGN_GCC_R46_OV_TLS_CA_2025_SHA256,
    ),
}


def der_sha256(pem: str) -> str:
    body = "".join(
        line for line in pem.strip().splitlines() if line and not line.startswith("-----")
    )
    return hashlib.sha256(base64.b64decode(body)).hexdigest()


def context_for(host: str) -> ssl.SSLContext | None:
    """A verifying TLS context with the host's extra intermediate, or None."""
    entry = EXTRA_INTERMEDIATES.get(host)
    if entry is None:
        return None
    pem, expected = entry
    if der_sha256(pem) != expected:
        raise ElectionReportError(f"pinned intermediate certificate for {host} does not match its SHA-256")
    context = ssl.create_default_context()
    context.load_verify_locations(cadata=pem)
    return context
